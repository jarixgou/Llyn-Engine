std::string GetVkResultMessage(VkResult _result);
std::string GetSpvResultMessage(SpvReflectResult _result);

void VkCheck(int _result, const std::string& _message)
{
	if (_result == VK_SUCCESS)
	{
		return;
	}
	const std::string result = GetVkResultMessage(static_cast<VkResult>(_result));

	const std::string finalMessage = _message + " " + result;

	LOGGER_CRITICAL(finalMessage);
}

void SpvCheck(int _result, const std::string& _message)
{
	if (_result == SPV_REFLECT_RESULT_SUCCESS)
	{
		return;
	}
	const std::string result = GetSpvResultMessage(static_cast<SpvReflectResult>(_result));

	const std::string finalMessage = _message + " " + result;

	LOGGER_CRITICAL(finalMessage);
}

